#!/usr/bin/env bash
# Asks for the credentials of the DNS provider (ACME_DNS_PROVIDER in .env),
# with which Traefik proves the domain to Let's Encrypt. Each secret is typed
# without being shown and saved in its own file in secrets/acme-dns/ (rights
# 600); secrets/acme-dns.env only gives Traefik the paths to these files.
# Present credentials are kept: to replace them, or to change provider,
# delete secrets/acme-dns.env and secrets/acme-dns/, then run it again.
# app@install runs it in prod.
#
# @usage make cert@dns
set -euo pipefail
. "$(dirname "$0")/../lib.sh"

load_env cert@dns
require_app_env cert@dns prod

provider="${ACME_DNS_PROVIDER:-}"
[ -n "$provider" ] \
  || die "cert@dns : ACME_DNS_PROVIDER absent du .env (ex. ACME_DNS_PROVIDER=ovh)"

if [ -f "$ACME_DNS_ENV" ]; then
  saved="$(sed -n 's/^# provider: //p' "$ACME_DNS_ENV")"
  [ "$saved" = "$provider" ] \
    || die "cert@dns : identifiants enregistrés pour « $saved », pas « $provider » — supprimer $ACME_DNS_ENV et $ACME_DNS_DIR/, puis relancer"
  info "Identifiants DNS déjà présents ($provider)."
  exit 0
fi

# Per provider (names from https://go-acme.github.io/lego/dns/): secret
# variables, asked without being shown; fixed settings; where to create the
# credentials. Another provider: add a case with its variables.
settings=()
case "$provider" in
  ovh)
    secrets=(OVH_APPLICATION_KEY OVH_APPLICATION_SECRET OVH_CONSUMER_KEY)
    settings=(OVH_ENDPOINT=ovh-eu)
    help="https://eu.api.ovh.com/createToken/ — droits POST et DELETE sur /domain/zone/${ACME_DOMAIN:-<domaine>}/*"
    ;;
  cloudflare)
    secrets=(CF_DNS_API_TOKEN)
    help="https://dash.cloudflare.com/profile/api-tokens — jeton « Zone → DNS → Edit » sur la zone ${ACME_DOMAIN:-<domaine>}"
    ;;
  gandiv5)
    secrets=(GANDIV5_PERSONAL_ACCESS_TOKEN)
    help="https://account.gandi.net/ — jeton d'accès personnel, droit « Gérer la configuration technique des domaines »"
    ;;
  *)
    die "cert@dns : fournisseur « $provider » inconnu de ce script — ajouter ses variables dans .make/scripts/cert/dns.sh (voir https://go-acme.github.io/lego/dns/)"
    ;;
esac

[ -t 0 ] || die "cert@dns : identifiants DNS absents, à saisir dans un terminal — lancer « make cert@dns »"

info "Identifiants du fournisseur DNS « $provider », à créer sur :"
info "$help"
info "La saisie n'est pas affichée."

# Everything created below is unreadable by others.
umask 077
mkdir -p "$ACME_DNS_DIR"
env_lines=("# provider: $provider" "# Generated by make cert@dns. Secret values are in $ACME_DNS_DIR/.")
for setting in "${settings[@]}"; do
  env_lines+=("$setting")
done
for var in "${secrets[@]}"; do
  value=""
  while [ -z "$value" ]; do
    read -rsp "  $var : " value
    printf '\n'
  done
  printf '%s' "$value" > "$ACME_DNS_DIR/$var"
  env_lines+=("${var}_FILE=/run/secrets/acme-dns/$var")
done
# Written last: its presence means the credentials are complete.
printf '%s\n' "${env_lines[@]}" > "$ACME_DNS_ENV"
info "Identifiants enregistrés ($ACME_DNS_ENV, $ACME_DNS_DIR/)."

if proxy_running; then
  info "Le proxy tourne : « make app@restart » pour les prendre en compte."
fi
